import { expect, test } from '@playwright/test'

test('mode Pixel dan Normal mengingat pilihan, menampilkan angka yang sama dan hanya memuat ilustrasi di ringkasan', async ({ page }) => {
  await page.setViewportSize({ width: 1366, height: 900 })
  const art: string[] = []
  await page.route('**/assets/**', async route => {
    if (/\/(?:workshop|benches|crew|metrics)-[^/]+\.png(?:\?|$)/.test(route.request().url())) art.push(route.request().url())
    await route.continue()
  })
  await page.goto('/')
  const mode = page.getByRole('group', { name: 'Tampilan ringkasan bisnis' })
  const pixel = mode.getByRole('button', { name: 'Pixel' })
  const normal = mode.getByRole('button', { name: 'Normal' })
  const scene = page.getByRole('figure', { name: 'Lantai produksi' })
  await expect(pixel).toHaveAttribute('aria-pressed', 'true')
  await expect(scene).toBeVisible()
  await expect.poll(() => new Set(art).size).toBe(4)
  const amounts = await page.locator('.kpi-value').allTextContents()
  const ledger = await page.locator('.chart-legend').innerText()
  await normal.click()
  await expect(scene).toHaveCount(0)
  await expect(page.locator('.kpi-value')).toHaveText(amounts)
  expect(await page.locator('.chart-legend').innerText()).toBe(ledger)
  await page.locator('.topbar').getByRole('button', { name: 'Tampilan lama', exact: true }).click()
  art.length = 0
  await page.reload()
  await expect(normal).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('html')).not.toHaveClass(/ux-rapih/)
  await expect(page.locator('.kpi-value')).toHaveText(amounts)
  expect(art).toHaveLength(0)
  await pixel.click()
  await expect(scene).toBeVisible()
  await expect(page.locator('html')).not.toHaveClass(/ux-rapih/)
  await expect.poll(() => new Set(art).size).toBe(4)
  art.length = 0
  await page.goto('/keuangan/hpp/')
  await expect(page.getByRole('heading', { name: /HPP/ }).first()).toBeVisible()
  await expect(mode).toHaveCount(0)
  await expect(scene).toHaveCount(0)
  expect(art).toHaveLength(0)
})

test('gerakan kru bisa dijeda, berhenti saat gulir, dan mengikuti Kurangi Gerakan', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 740 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/')
  const scene = page.getByRole('figure', { name: 'Lantai produksi' })
  const courier = scene.locator('.atelier-walk-route')
  await expect(courier).toHaveCSS('animation-play-state', 'paused')
  await scene.getByRole('button', { name: 'Putar animasi' }).click()
  await expect(courier).toHaveCSS('animation-play-state', 'running')
  const first = await courier.evaluate(el => getComputedStyle(el).transform)
  await expect.poll(() => courier.evaluate(el => getComputedStyle(el).transform)).not.toBe(first)
  await page.locator('.flow-strip').scrollIntoViewIfNeeded()
  await expect(courier).toHaveCSS('animation-play-state', 'paused')
  await scene.scrollIntoViewIfNeeded()
  await expect(courier).toHaveCSS('animation-play-state', 'running')
  await scene.getByRole('button', { name: 'Jeda animasi' }).click()
  await expect(courier).toHaveCSS('animation-play-state', 'paused')
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.reload()
  await expect(scene.getByRole('button', { name: 'Putar animasi' })).toBeVisible()
  await expect(courier).toHaveCSS('animation-play-state', 'paused')
})
