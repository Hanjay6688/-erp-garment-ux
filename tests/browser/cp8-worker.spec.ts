import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import JSZip from 'jszip'

async function openGroup(page: Page, name: string) {
  const menu = page.getByRole('button', { name: 'Buka menu', exact: true })
  if (await menu.isVisible()) await menu.click()
  await page.locator('aside.sidebar').getByRole('button', { name: new RegExp('^' + name) }).click()
}
async function pageFits(page: Page) {
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth + 1)).toBe(true)
}

for (const width of [320, 390, 768, 1440]) {
  test(`Gladi Worker pada ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    const crashes: string[] = []
    page.on('pageerror', error => crashes.push(error.message))
    await page.goto('/')
    await expect(page.getByRole('heading',{ name:'Veni. Vidi. Vici. ERP' })).toBeVisible()
    await expect(page.locator('.kpi-grid')).toContainText('Rp284,6 jt')
    await expect(page.locator('html')).toHaveClass(/ux-rapih/)
    await expect(page.locator('.topbar')).toHaveCSS('border-bottom-color','rgb(47, 59, 90)')
    await pageFits(page)
    await page.getByRole('button',{name:'Input penjualan'}).click()
    await page.getByRole('button',{name:'Review invoice'}).click()
    await expect(page.getByRole('dialog')).toContainText('72 pcs')
    await page.getByRole('button',{name:'Simpan Draft + reserve'}).click()
    await expect(page.getByText(/Draft tersimpan\. Mutasi RESERVE INVOICE/)).toContainText('−72 pcs')
    await openGroup(page,'Keuangan')
    await page.getByRole('button',{name:/• Kas & Bank/}).click()
    const cashRows = page.locator('.biz-table.cash > article')
    await expect(cashRows.first()).toBeVisible()
    // Measure rendered text, including wrapped lines and nested dates, inside the scrollable table.
    const gaps = await cashRows.evaluateAll(rows => rows.flatMap(row => {
      const ink = Array.from(row.children, cell => {
        const walker = document.createTreeWalker(cell, NodeFilter.SHOW_TEXT)
        const bounds: DOMRect[] = []
        for (let node = walker.nextNode(); node; node = walker.nextNode()) {
          if (!node.textContent?.trim()) continue
          const range = document.createRange()
          range.selectNodeContents(node)
          bounds.push(...Array.from(range.getClientRects()))
        }
        return { left: Math.min(...bounds.map(box => box.left)), right: Math.max(...bounds.map(box => box.right)) }
      })
      return ink.slice(1).map((cell, index) => cell.left - ink[index].right)
    }))
    expect(gaps.length).toBeGreaterThan(0)
    expect(Math.min(...gaps), 'Jarak tulisan antarkolom kas').toBeGreaterThanOrEqual(6)
    await pageFits(page)
    await openGroup(page,'Pengaturan & Audit')
    await page.getByRole('button',{name:/• Impor data awal/}).click()
    await page.getByRole('button',{name:'Coba data contoh'}).click()
    await expect(page.getByRole('status')).toContainText('9 baris dalam 5 tab')
    await pageFits(page)
    const saved = page.waitForEvent('download')
    await page.getByRole('button',{name:'Unduh paket CSV'}).click()
    const download = await saved
    const zip = await JSZip.loadAsync(await readFile((await download.path())!))
    expect(Object.keys(zip.files).filter(f => f.endsWith('.csv'))).toHaveLength(5)
    expect(await zip.file('CUSTOMER.csv')!.async('string')).toContain('00017')
    await openGroup(page,'Analisis & Planner')
    await page.getByRole('link',{name:'Business Report'}).click()
    await expect(page.getByRole('table')).toContainText('WIP potensial')
    await expect(page.getByRole('table')).toContainText('18 pcs')
    await page.reload()
    await expect(page.getByRole('table')).toContainText('18 pcs')
    await pageFits(page)
    await page.getByRole('button',{name:'Prioritas produksi'}).click()
    await expect(page.getByRole('heading',{name:'Tindakan yang perlu ditinjau'})).toBeVisible()
    await page.getByRole('button',{name:'Lihat detail'}).first().click()
    await expect(page.getByRole('dialog')).toBeVisible()
    await page.getByRole('button',{name:'Tutup detail'}).click()
    await expect(page.locator('.gar-plan')).toHaveCount(4)
    await expect(page.locator('[data-sku="66002"]')).toContainText('Tunggu hasil produksi')
    await page.getByRole('button',{name:'Panel Potongan'}).click()
    await page.getByRole('button',{name:'Isi form · 18 pcs'}).click()
    await expect(page.getByRole('heading',{name:'Buat Potongan',exact:true})).toBeVisible()
    await expect(page.getByLabel('SKU rencana')).toHaveValue('93001')
    await expect(page.locator('.cutting-pattern-picker > header')).toContainText('KJ · R2')
    await expect(page.locator('.stock-roll-row.selected')).toContainText('1069 Ori')
    await expect(page.getByRole('textbox',{name:'Roll 1, size 32',exact:true})).toHaveValue('18')
    await pageFits(page)
    await page.getByRole('button',{name:'Simpan Potongan ke WIP'}).click()
    await expect(page.getByRole('status').filter({hasText:'POT-D01 tersimpan'})).toBeVisible()
    await expect(page.getByRole('button',{name:'Simpan Potongan ke WIP'})).toBeDisabled()
    await page.getByRole('link',{name:'Bagi POT-D01',exact:true}).click()
    await expect(page.locator('.wip-selected-head')).toContainText('POT-D01 · Vivo 93001')
    await page.getByRole('button',{name:'Pilih POT-017',exact:true}).click()
    await expect(page.locator('.wip-selected-head')).toContainText('POT-017 · Widie 66001')
    await expect(page.locator('.wip-selected-head')).toContainText('24 pcs')
    await pageFits(page)
    await page.getByRole('button',{name:'Catat pickup POT-017'}).click()
    await expect(page.getByRole('status').filter({hasText:'POT-017 · 24 pcs'})).toBeVisible()
    await expect(page.getByRole('button',{name:'Catat pickup POT-017'})).toHaveCount(0)
    await page.goto('/analisis/planner/')
    await expect(page.locator('[data-sku="93001"]')).not.toContainText('Potong 18 pcs')
    await expect(page.locator('[data-sku="66001"]')).toContainText('Tunggu hasil produksi')
    await page.locator('[data-sku="66003"]').getByRole('button',{name:'Lihat detail'}).click()
    await expect(page.getByRole('dialog')).toContainText('Black Virgo')
    await expect(page.getByRole('dialog')).toContainText('Lewat tenggat')
    await page.getByRole('link',{name:'Cek jahitan Mandor Selo'}).click()
    await page.getByRole('button',{name:'Pastikan tujuan 66003'}).click()
    await page.getByRole('link',{name:'Kembali ke Planner'}).click()
    await expect(page.locator('[data-sku="66003"]')).toContainText('Tunggu hasil produksi')
    await page.reload()
    await expect(page.locator('[data-sku="66001"]')).toContainText('Tunggu hasil produksi')
    expect(crashes).toEqual([])
  })
}

test('Jahitan untuk pesanan lain membuka dua pilihan bahan dan mempertahankan ukuran fisik',async({page})=>{
  await page.goto('/produksi/jahit/?lot=JHT-044')
  await page.getByRole('button',{name:'Untuk pesanan lain'}).click()
  await page.getByRole('link',{name:'Kembali ke Planner'}).click()
  await expect(page.locator('[data-sku="66003"]')).toContainText('Potong 12 pcs')
  await page.getByRole('button',{name:'Panel Potongan'}).click()
  await page.getByLabel('Pilih bahan untuk 66003').selectOption('Black Virgo')
  await page.getByRole('button',{name:'Isi form · 12 pcs'}).click()
  await expect(page.getByLabel('SKU rencana')).toHaveValue('66003')
  await expect(page.locator('.stock-roll-row.selected')).toContainText('Black Virgo')
  await expect(page.getByRole('textbox',{name:'Roll 5, size 30',exact:true})).toHaveValue('12')
  await page.getByRole('button',{name:'Simpan Potongan ke WIP'}).click()
  await expect(page.getByText(/54 yd sebelum dipotong/)).toContainText('sisa 39 yd')
  await page.getByRole('link',{name:'Bagi POT-D01',exact:true}).click()
  await expect(page.locator('.wip-selected-head')).toContainText('ukuran 30')
  await page.getByRole('button',{name:'Catat pickup POT-D01'}).click()
  await page.getByRole('link',{name:'Lihat stok dan WIP'}).click()
  await page.getByRole('button',{name:'Widie 66003'}).click()
  await expect(page.getByRole('dialog')).toContainText('Untuk pesanan lain')
  await expect(page.getByRole('dialog')).toContainText('Lewat tenggat')
  await expect(page.getByRole('dialog').locator('dl>div').filter({hasText:'Sisa perlu potong'})).toContainText('0 pcs')
})
