test('scroll sentuh di dropdown tidak membuka pilihan, tap dan keyboard tetap bekerja', async ({ browser, baseURL }) => {
  const context = await browser.newContext({ baseURL, viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  try {
    const page = await context.newPage()
    await page.goto('/produksi/laundry/')
    const vendor = page.getByLabel('Laundry terpilih', { exact: true })
    await vendor.scrollIntoViewIfNeeded()
    const box = (await vendor.boundingBox())!
    const x = Math.round(box.x + box.width / 2)
    const y = Math.round(box.y + box.height / 2)
    const cdp = await context.newCDPSession(page)
    const touch = page.getByRole('dialog', { name: 'Laundry terpilih' })
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y, id: 1 }] })
    await expect(touch).toHaveCount(0)
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y: y - 30, id: 1 }] })
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y: y - 70, id: 1 }] })
    await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    // During momentum scrolling Chromium can consume a touch to stop the scroll.
    await page.evaluate(() => new Promise<void>(resolve => {
      let lastY = scrollY
      let stable = 0
      function frame() {
        stable = scrollY === lastY ? stable + 1 : 0
        lastY = scrollY
        if (stable >= 10) resolve()
        else requestAnimationFrame(frame)
      }
      requestAnimationFrame(frame)
    }))
    await expect(touch).toHaveCount(0)
    await vendor.tap()
    await expect(touch).toBeVisible()
    await touch.getByRole('option', { name: 'Laundry Intan' }).tap()
    await expect(vendor).toHaveValue('Laundry Intan')
    await vendor.press('Enter')
    await expect(touch).toBeVisible()
  } finally {
    await context.close()
  }
})

